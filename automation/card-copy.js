/* 아이템 개수를 우리말로. 카드 푸터·캡션에 쓴다. */
const COUNT_WORD = ['', '한 가지', '두 가지', '세 가지', '네 가지', '다섯 가지', '여섯 가지', '일곱 가지', '여덟 가지'];

/* 손으로 쓴 카피가 없을 때 쓰는 폴백.
   VIDEO_NOTES(영상마다 사람이 쓴 한 문장)를 재료로 쓴다. 사람 카피보다 심심하지만
   카드가 아예 안 나오는 것보다는 낫다. auto: true 로 표시해서 텔레그램 보고에
   "카피 자동 생성 — 확인 필요"가 붙게 한다. */
function buildFallback({ destName, note, productCount }) {
  const cnt = COUNT_WORD[productCount] || `${productCount}가지`;
  const trimmed = String(note || '').replace(/\s*이에요\.?$|\s*예요\.?$|\s*해요\.?$/, '');
  return {
    auto: true,
    badge: '이게 뭐길래',
    headline: ['오늘의', '꿀템 쇼츠'],
    sub: [`${destName} 쇼츠에서 꼽은`, '아이템을 정리해뒀어요.'],
    foot: productCount ? `${cnt} 정리해뒀어요` : '정리해뒀어요',
    hook: `${destName} 쇼츠 중에 조회수 {views}만짜리가 있는데`,
    detail: trimmed ? `${trimmed}더라고요` : '아이템을 정리해뒀어요',
    dcTitle: `${destName} 갈 때 뭐 챙겨감?`,
    dcBody: `조회수 {views}만 찍은 쇼츠 보다가 알았는데 나는 안 챙긴 게 꽤 있더라`,
  };
}

/* 채널별 말투는 여기서 한 번만 정의한다. 영상마다 다시 쓰지 않는다. */
function buildCaptions({ copy, slug, views, youtubeId }) {
  const link = (src) => `https://shortsbox.kr/watch/${youtubeId}/?utm_source=${src}&utm_medium=social`;
  const fill = (s) => String(s).replace(/\{views\}/g, views);
  const hook = fill(copy.hook);
  const detail = fill(copy.detail);
  const tags = (HASHTAGS[slug] || ['#여행꿀템', '#여행준비물', '#여행스타그램']).join(' ');

  return {
    threads: `${hook} 😳 ${detail}. 뭔지 링크에 정리해뒀어요 ${link('threads')}`,
    instagram: `${hook}.\n${detail}.\n\n🔗 프로필 링크에서 확인해보세요\n\n${tags}`,
    x: `${detail} 😳 ${link('x')}`,
    kakao: `${hook} 😅\n${detail}.\n여기 정리해뒀어요 ${link('kakao')}`,
    dcinside_title: fill(copy.dcTitle),
    dcinside_body: `${fill(copy.dcBody)} ${link('dcinside')}`,
  };
}

module.exports = { CARD_COPY, HASHTAGS, COUNT_WORD, buildFallback, buildCaptions };
